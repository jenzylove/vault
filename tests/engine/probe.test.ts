/**
 * Incentive probe: 500 seeded SIMULATED players per strategy play the real reducer.
 * Writes the table to docs/probe.md. If an assertion fails, fix the RULES, not this test.
 */
import { beforeAll, describe, expect, test } from 'vitest';
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import {
  runSimGame, readBanker, bankerView, newGame, step, signalWeights, learnBaseline, extractFeatures, SimBody,
  makeSimPlayer, RULES, MAX_STRIKES, OFFER_FLOOR, OFFER_WINDOW_MS, BANKER_RULES, PRIOR, LEVELS, DEFAULT_LEVEL, type SimGameResult, type Strategy, type Policy,
  type PeekFeatures, type GameState, type LevelNo, BASELINE_MS, PEEK_MS,
} from '../../src/renderer/engine';
import { wantsToSell } from '../../src/renderer/engine/autoplay';
import { emptyModel, learnExample } from '../../src/renderer/engine/banker';

const N = 400;
const ROWS: { key: string; strategy: Strategy; policy: Policy; label: string }[] = [
  { key: 'honest', strategy: 'honest', policy: 'rational', label: 'Honest (natural tells)' },
  { key: 'steady', strategy: 'steady', policy: 'rational', label: 'Always steady (skilled breath control)' },
  { key: 'fakeGasp', strategy: 'fakeGasp', policy: 'rational', label: 'Fake gasp at treasure' },
  { key: 'freeze', strategy: 'freeze', policy: 'rational', label: 'Freeze blank every peek' },
  { key: 'holdBreath', strategy: 'holdBreath', policy: 'rational', label: 'Hold breath every peek' },
  { key: 'fakeSmile', strategy: 'fakeSmile', policy: 'rational', label: 'Fake smile at traps only' },
  { key: 'hide', strategy: 'hide', policy: 'rational', label: 'Duck out of camera at traps' },
  { key: 'steadyGreedy', strategy: 'steady', policy: 'greedy', label: 'Always steady, ignores strikes (sells every dud)' },
];

const all: Record<number, Record<string, SimGameResult[]>> = {};
let results: Record<string, SimGameResult[]> = {};
/** the same runs, but every player bets the last safe double or nothing */
const bets: Record<string, SimGameResult[]> = {};
const avg = (xs: number[]): number => xs.reduce((a, x) => a + x, 0) / Math.max(1, xs.length);
const se = (xs: number[]): number => {
  const m = avg(xs);
  return Math.sqrt(xs.reduce((a, x) => a + (x - m) ** 2, 0) / Math.max(1, xs.length - 1) / Math.max(1, xs.length));
};
/** Paired difference vs honest: same seed = same body, same box order. */
const paired = (key: string, base = 'honest', res = results): { mean: number; se: number } => {
  const a = res[key]!;
  const b = res[base]!;
  const d = a.map((r, i) => r.pile - b[i]!.pile);
  return { mean: avg(d), se: se(d) };
};
const col = (key: string, f: (r: SimGameResult) => number, res = results): number => avg(res[key]!.map(f));
const winRate = (key: string, res: Record<string, SimGameResult[]>): number => col(key, (r) => (r.won ? 1 : 0), res);

beforeAll(() => {
  for (const L of LEVELS) {
    const res: Record<string, SimGameResult[]> = {};
    for (const row of ROWS) {
      res[row.key] = Array.from({ length: N }, (_, i) => runSimGame(row.strategy, i + 1, { policy: row.policy, fps: 15, level: L.level }));
    }
    all[L.level] = res;
  }
  results = all[DEFAULT_LEVEL]!;
  for (const row of ROWS) {
    bets[row.key] = Array.from({ length: N }, (_, i) => runSimGame(row.strategy, i + 1, { policy: row.policy, fps: 15, level: DEFAULT_LEVEL, final: 'bet' }));
  }
  const fmt = (x: number, d = 0): string => x.toFixed(d);
  const pctOf = (x: number): string => `${x >= 0 ? '+' : ''}${fmt(100 * x)}%`;
  const levelSections = LEVELS.flatMap((L) => {
    const res = all[L.level]!;
    const hon = col('honest', (r) => r.pile, res);
    const sig = Object.entries(L.signals).filter(([, on]) => on).map(([k]) => k).join(', ');
    return [
      `### Bank ${L.level}: ${L.rank}`,
      '',
      `Reads: ${sig}. Learning weight ${L.learnWeight}, walks at P(trap) ${L.walkAt}, base margin ${L.marginBase}. Beat him: bank ${L.target}, he catches at most ${L.maxTrapsCaught} of your traps, he burns at most ${L.maxBurned} of your treasures.`,
      '',
      '| Strategy | Mean pile | vs honest | Beat the banker | Busted |',
      '|---|---:|---:|---:|---:|',
      ...ROWS.map((row) => {
        const m = col(row.key, (r) => r.pile, res);
        return `| ${row.label} | ${fmt(m)} | ${row.key === 'honest' ? '' : pctOf(m / hon - 1)} | ${fmt(100 * winRate(row.key, res))}% | ${fmt(100 * col(row.key, (r) => (r.busted ? 1 : 0), res))}% |`;
      }),
      '',
    ];
  });
  const lines = [
    '# Incentive probe',
    '',
    `${N} seeded **simulated** players per strategy (same seeds, same bodies, same box order across rows), playing the real game reducer. The main table is the default banker (Bank ${DEFAULT_LEVEL}); every bank is below.`,
    'Generated by `tests/engine/probe.test.ts` from the simulated body in `src/renderer/engine/sim.ts`. Not recorded people.',
    '',
    '| Strategy | Mean pile | vs honest (paired) | Traps sold | Treasures burned | Banker accuracy | Chance | Busted | Walked out |',
    '|---|---:|---:|---:|---:|---:|---:|---:|---:|',
    ...ROWS.map((row) => {
      const p = paired(row.key);
      return `| ${row.label} | ${fmt(col(row.key, (r) => r.pile))} ± ${fmt(se(results[row.key]!.map((r) => r.pile)))} | ${row.key === 'honest' ? '' : `${p.mean >= 0 ? '+' : ''}${fmt(p.mean)} ± ${fmt(p.se)}`} | ${fmt(col(row.key, (r) => r.trapsSold), 2)} | ${fmt(col(row.key, (r) => r.treasuresBurned), 2)} | ${fmt(100 * col(row.key, (r) => r.bankerAccuracy))}% | ${fmt(100 * col(row.key, (r) => r.chanceAccuracy))}% | ${fmt(100 * col(row.key, (r) => (r.busted ? 1 : 0)))}% | ${fmt(100 * col(row.key, (r) => (r.left ? 1 : 0)))}% |`;
    }),
    '',
    '± is one standard error. "Chance" is the accuracy a banker with the same walk rate but no read of the player would get on the same boxes.',
    '',
    `Fake smile: once he has seen your real smile at a big treasure, copying it at a trap can lift his price a little (${paired('fakeSmile').mean.toFixed(0)} ± ${paired('fakeSmile').se.toFixed(0)} a run at this bank, under 1%). It sells no more traps and wins no more often. Banks 1 and 2 cannot read a face, so there it changes nothing.`,
    '',
    '## The last safe: double or nothing',
    '',
    `Same ${N} seeds at Bank ${DEFAULT_LEVEL}, but every player bets the last safe instead of walking out. He calls loot or dud; a right call takes the whole take, a wrong one doubles it. Fooling him is the only way to win the bet, so this is where a bluff pays. The probe rows above all walk out.`,
    '',
    '| Strategy | Bets made | He called it wrong (you doubled) | Mean pile when betting | vs walking out |',
    '|---|---:|---:|---:|---:|',
    ...ROWS.map((row) => {
      const b = bets[row.key]!.filter((r) => r.finalBet);
      const won = b.filter((r) => r.finalCall && !r.finalCall.right).length;
      const m = col(row.key, (r) => r.pile, bets);
      const w = col(row.key, (r) => r.pile);
      return `| ${row.label} | ${fmt(100 * b.length / N)}% | ${b.length ? fmt(100 * won / b.length) : '0'}% | ${fmt(m)} | ${m - w >= 0 ? '+' : ''}${fmt(m - w)} |`;
    }),
    '',
    '## He remembers you',
    '',
    'Three jobs in a row with his memory of each player carried from job to job: see [probe-memory.md](probe-memory.md) (written by `tests/engine/memory-probe.test.ts`).',
    '',
    '## The banker ladder',
    '',
    ...levelSections,
    '## Rules in force',
    '',
    `- Strikes: a dud the banker buys and finds at its audit is ${RULES.strikesPerDudFound} strike. At ${MAX_STRIKES} strikes you are busted and leave with ${RULES.bustKeep * 100}% of your pile. Nothing else busts you.`,
    `- Heat is his suspicion only: +${RULES.heatPerTrapBought} per dud he found, +${RULES.heatUnread} per unread peek, up to +${RULES.pulseHeatMax} from a rising pulse. It lowers his offers and makes him quicker to pass.`,
    `- Ticking offer: his offer falls from 100% to ${OFFER_FLOOR * 100}% over ${OFFER_WINDOW_MS / 1000} s; the simulated players answer at once, so they get the full offer.`,
    `- Last safe: with one safe left and a take on the line you may walk out or bet the take double or nothing on his call. The simulated players walk out (the default policy).`,
    `- Heist: a trap you sold pays its price again (×${RULES.heistBonus}) when the banker's audit finds it (not on a blind offer).`,
    `- Heat from pulse counts only for banks that read pulse (4 and 5).`,
    `- The banker never buys a box where it saw you catch your breath. A box it lost you at that turns out to be a trap counts as caught.`,
    `- Banker walks when P(trap) ≥ its level's walk point − ${BANKER_RULES.walkHeatSlope} × heat (floor ${BANKER_RULES.walkFloor}). Offer = its estimate of a treasure's value × (1 − margin), margin = level base + ${BANKER_RULES.marginHeat} × heat + ${BANKER_RULES.marginDoubt} × (1 − banker's own hit rate).`,
    `- Unread peeks get a blind offer at ${BANKER_RULES.unreadDiscount * 100}%, priced from what this player's unread boxes turned out to be.`,
    `- Banker model: per player Gaussian naive Bayes on breath catch, shallowing, rate change, blinks, smile, alarm; priors with ${PRIOR.breathPseudo} pseudo counts per class for breath and ${PRIOR.pseudo} for the rest, updated by every audit (and by 2 labelled practice peeks when the player takes them; the probe skips them, as most runs do) (each labelled box weighted by the level's learning weight). Signals a level can't read contribute nothing.`,
    '',
    '## Simulated player policy',
    '',
    `- A run is up to ${RULES.boxesPerRun} peeks out of 10 boxes, picked at random; 10 s calm, 5 s peeks, no practice; it walks out at the last safe when it has a take.`,
    '- Sells a treasure only when the offer beats its value; opens it otherwise.',
    '- Sells a dud whenever offered, unless the strike would bust it (rational); the greedy row sells every dud.',
  ];
  writeFileSync(resolve(__dirname, '../../docs/probe.md'), lines.join('\n') + '\n');
}, 1500000);

describe('incentive probe (simulated players)', () => {
  test('skilled breath control wins on average', () => {
    const d = paired('steady');
    expect(d.mean).toBeGreaterThan(3 * d.se);
    // and clearly: robbing the banker should feel like it pays (15 to 25% over honest)
    expect(col('steady', (r) => r.pile)).toBeGreaterThan(1.15 * col('honest', (r) => r.pile));
    expect(col('steady', (r) => r.trapsSold)).toBeGreaterThan(col('honest', (r) => r.trapsSold) + 0.5);
  });

  test('faking a gasp at treasure loses: the banker burns treasures', () => {
    const d = paired('fakeGasp');
    expect(d.mean).toBeLessThan(-3 * d.se);
    expect(col('fakeGasp', (r) => r.treasuresBurned)).toBeGreaterThan(col('honest', (r) => r.treasuresBurned) + 0.4);
  });

  test('freezing and holding the breath lose', () => {
    for (const k of ['freeze', 'holdBreath']) {
      const d = paired(k);
      expect(d.mean).toBeLessThan(-3 * d.se);
      expect(col(k, (r) => r.treasuresBurned)).toBeGreaterThan(1);
    }
  });

  test('a fake smile alone does not fool a banker whose learned weights favour breath', () => {
    expect(col('fakeSmile', (r) => r.trapsSold)).toBeLessThanOrEqual(col('honest', (r) => r.trapsSold) + 0.05);
    expect(col('fakeSmile', (r) => r.bankerAccuracy)).toBeGreaterThanOrEqual(col('honest', (r) => r.bankerAccuracy) - 0.02);
    // Copying the smile he learned at your real big treasure can lift his price on a trap a little.
    // It must stay a rounding error: under 1% of the pile, and nowhere near what real breath control earns.
    const fs = paired('fakeSmile');
    expect(fs.mean).toBeLessThan(0.01 * col('honest', (r) => r.pile));
    expect(paired('fakeSmile').mean).toBeLessThan(paired('steady').mean / 10);
    // and after the practice peeks breath carries more weight than the face for most smilers
    let breathWins = 0;
    for (let seed = 1; seed <= 60; seed++) {
      const p = { ...makeSimPlayer('fakeSmile', seed), talkProb: 0 };
      const body = new SimBody(p, seed, 15);
      const bl = learnBaseline(body.run(BASELINE_MS));
      let m = emptyModel();
      for (const kind of ['trap', 'small'] as const) {
        body.run(1500); body.react(kind);
        m = learnExample(m, extractFeatures(body.run(PEEK_MS), bl), kind);
      }
      const w = signalWeights(m);
      if (w.breath > w.face) breathWins++;
    }
    expect(breathWins).toBeGreaterThan(40);
  });

  test('ducking out of camera does not pay', () => {
    expect(paired('hide').mean).toBeLessThan(0);
    const g = paired('steadyGreedy');
    expect(g.mean).toBeLessThan(-3 * g.se); // greedy ignoring strikes loses to honest too
  });

  test('the banker reads honest players better than chance', () => {
    expect(col('honest', (r) => r.bankerAccuracy)).toBeGreaterThan(col('honest', (r) => r.chanceAccuracy) + 0.15);
  });
});

describe('banker ladder (simulated players, every level)', () => {
  const levels = (): LevelNo[] => LEVELS.map((L) => L.level);

  test('honest players beat Bank 1 often and Bank 5 rarely', () => {
    expect(winRate('honest', all[1]!)).toBeGreaterThan(0.3);
    expect(winRate('honest', all[5]!)).toBeLessThan(0.1);
    // each bank is at least as hard as the one before for an honest player (small noise allowed)
    for (const L of levels().slice(1)) expect(winRate('honest', all[L]!)).toBeLessThanOrEqual(winRate('honest', all[L - 1]!) + 0.03);
  });

  test('skilled steady beats honest at every level, by a clear margin, and climbs best', () => {
    for (const L of levels()) {
      const res = all[L]!;
      const d = paired('steady', 'honest', res);
      expect(d.mean).toBeGreaterThan(3 * d.se);
      expect(col('steady', (r) => r.pile, res)).toBeGreaterThan(1.1 * col('honest', (r) => r.pile, res));
      for (const k of ['honest', 'fakeGasp', 'freeze', 'holdBreath', 'fakeSmile', 'hide', 'steadyGreedy']) {
        expect(winRate('steady', res)).toBeGreaterThan(winRate(k, res));
      }
    }
  });

  test('faking, freezing, holding, hiding and ignoring strikes lose to honest at every level; fake smile gains under 1%', () => {
    for (const L of levels()) {
      const res = all[L]!;
      for (const k of ['fakeGasp', 'freeze', 'holdBreath', 'hide', 'steadyGreedy']) {
        const d = paired(k, 'honest', res);
        expect(d.mean).toBeLessThan(-2 * d.se);
      }
      const fs = paired('fakeSmile', 'honest', res);
      expect(fs.mean).toBeLessThan(0.01 * col('honest', (r) => r.pile, res)); // exactly 0 at banks that cannot read a face
    }
  });

  test('no faking strategy beats the banker more often than an honest player, at any bank', () => {
    for (const L of levels()) {
      const res = all[L]!;
      const honest = winRate('honest', res);
      for (const k of ['fakeGasp', 'holdBreath', 'freeze', 'hide']) expect(winRate(k, res)).toBeLessThanOrEqual(honest);
      // a fake smile changes nothing at banks that can't read faces; allow one game in 100 of noise elsewhere
      expect(winRate('fakeSmile', res)).toBeLessThanOrEqual(honest + 0.01);
    }
  });

  test('ignoring strikes busts you at every level', () => {
    for (const L of levels()) expect(col('steadyGreedy', (r) => (r.busted ? 1 : 0), all[L]!)).toBeGreaterThan(0.1);
  });
});

describe('every number on screen changes an outcome', () => {
  function boardState(): GameState {
    let s = step(newGame(5), { type: 'begin' });
    s = step(s, { type: 'baselineDone', baseline: learnBaseline(new SimBody(makeSimPlayer('honest', 5), 5, 15).run(BASELINE_MS)) });
    return step(s, { type: 'practiceDone', peeks: [] });
  }
  const mild: PeekFeatures = {
    breathCatchMs: 0, shallowing: 0.15, rateChange: 0.25, blinkBurst: 0.6, exprDelta: { surprise: 0.05 }, talking: false, pulseDelta: 0, quality: 1,
  };

  test('heat: lowers offers and turns an offer into a walk', () => {
    const s = boardState();
    const box = s.boxes[0]!;
    // some reads the banker would buy when cold, it walks away from when hot
    let flipped = 0;
    for (let k = 0; k <= 30; k++) {
      const f = { ...mild, shallowing: k * 0.03, rateChange: k * 0.03 };
      const cold = readBanker(emptyModel(), f, box, { ...bankerView(s), heat: 0 });
      const hot = readBanker(emptyModel(), f, box, { ...bankerView(s), heat: 0.9 });
      if (cold.decision === 'offer' && hot.decision === 'walk') flipped++;
      if (cold.decision === 'walk') expect(hot.decision).toBe('walk');
    }
    expect(flipped).toBeGreaterThan(0);
    const calm: PeekFeatures = { ...mild, shallowing: 0, rateChange: 0, blinkBurst: 0, exprDelta: {} };
    const o0 = readBanker(emptyModel(), calm, box, { ...bankerView(s), heat: 0 }).offer!;
    const o5 = readBanker(emptyModel(), calm, box, { ...bankerView(s), heat: 0.5 }).offer!;
    expect(o5).toBeLessThan(o0);
  });

  test('banker accuracy: a banker that has been wrong pays less', () => {
    const s = boardState();
    const calm: PeekFeatures = { ...mild, shallowing: 0, rateChange: 0, blinkBurst: 0, exprDelta: {} };
    const good = readBanker(emptyModel(), calm, s.boxes[0]!, { ...bankerView(s), correct: 6, calls: 6 }).offer!;
    const bad = readBanker(emptyModel(), calm, s.boxes[0]!, { ...bankerView(s), correct: 2, calls: 6 }).offer!;
    expect(bad).toBeLessThan(good);
  });

  test('offers: the same box is sold or opened depending on the offer', () => {
    const s = boardState();
    const small = s.boxes.find((b) => b.kind === 'small')!;
    const read = { pTrap: 0.2, pBig: 0.3, decision: 'offer' as const, reason: '', signal: 'none' as const };
    expect(wantsToSell({ ...s, read: { ...read, offer: small.value + 50 } }, 'small', small.value, 'rational')).toBe(true);
    expect(wantsToSell({ ...s, read: { ...read, offer: small.value - 50 } }, 'small', small.value, 'rational')).toBe(false);
    const sold = col('honest', (r) => r.treasuresSold);
    const opened = col('honest', (r) => r.treasuresOpened);
    expect(sold).toBeGreaterThan(0.2);
    expect(opened).toBeGreaterThan(0.75); // a run walks out at the last safe when it has a take, so 4 safes mostly
  });

  test('pile and strikes: ignoring strikes busts you and costs your pile', () => {
    const busts = col('steadyGreedy', (r) => (r.busted ? 1 : 0));
    expect(busts).toBeGreaterThan(0.1);
    const d = paired('steadyGreedy', 'steady');
    expect(d.mean).toBeLessThan(-3 * d.se);
  });

  test('spoken reasons never use the banned words', () => {
    const banned = /\b(lie|lies|lying|liar|stress|stressed|anxiety|anxious|poker|straight face)\b/i;
    const reasons = new Set<string>();
    for (let seed = 1; seed <= 25; seed++) {
      for (const strategy of ['honest', 'steady', 'fakeSmile', 'freeze', 'hide'] as const) {
        const p = makeSimPlayer(strategy, seed);
        const body = new SimBody(p, seed, 15);
        const bl = learnBaseline(body.run(BASELINE_MS));
        let s = step(step(step(newGame(seed), { type: 'begin' }), { type: 'baselineDone', baseline: bl }), { type: 'practiceDone', peeks: [] });
        for (const box of s.boxes.slice(0, 4)) {
          if (s.phase !== 'board') break;
          s = step(s, { type: 'choose', boxId: box.id });
          body.run(1000); body.react(box.kind);
          s = step(s, { type: 'peekDone', features: extractFeatures(body.run(PEEK_MS), bl) });
          if (s.read) reasons.add(s.read.reason);
          if (s.phase === 'bankerRead') s = step(s, { type: 'open' });
          if (s.phase === 'audit') s = step(s, { type: 'next' });
        }
      }
    }
    expect(reasons.size).toBeGreaterThan(5);
    for (const r of reasons) expect(r).not.toMatch(banned);
  }, 120000);
});
